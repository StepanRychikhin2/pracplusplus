#include <iostream> // Введення числа та виведення його цифр
#include <cctype>   // Перевірка пробілу після числа
#include <cstdio>   // Позначення кінця введення EOF
#ifdef _WIN32
#include <windows.h> // Українські літери в консолі Windows
#endif

using namespace std;

