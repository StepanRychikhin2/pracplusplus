#include <iostream> 
#include <iomanip>  
#include <cmath>    
#include <string>   
#include <windows.h> 
using namespace std;

int main()
{

    SetConsoleOutputCP(CP_UTF8);
    SetConsoleCP(CP_UTF8);
    // ---------- 1. Введення точності ----------
    // eps - точність: коли |член ряду| стане меншим за eps,
    // внутрішнє підсумовування припиняється ("нескінченність")
    double eps;
    cout << "Введіть точність eps (наприклад 1e-6): ";
    cin >> eps;

    // Межі для захисту від переповнення (за умовою завдання)
    const double MIN_LIMIT = 1e-38; // занадто малий член
    const double MAX_LIMIT = 1e+38; // занадто великий член

    // total - загальна сума по всіх x (результат подвійної суми)
    double total = 0;

    // ---------- 2. Шапка таблиці ----------
    // Чотири колонки: x, k, член ряду, накопичена сума
    cout << "\n"
         << setw(4) << "x"
         << setw(6) << "k"
         << setw(20) << "Член ряду"
         << setw(20) << "Сума" << "\n";
    cout << string(50, '-') << "\n";

    // ---------- 3. ЗОВНІШНЯ сума: цикл for по x ----------
    for (int x = 1; x <= 5; x++)
    {

        int k = 0; // номер поточного члена внутрішнього ряду

        // Перший член (k = 0) рахуємо напряму з формули:
        double a = 1.0 / x; // a - поточний член ряду

        double sum = a; // sum - накопичена сума ВНУТРІШНЬОГО ряду для цього x

        // Виводимо рядок таблиці для k = 0
        cout << fixed << setprecision(8)
             << setw(4) << x
             << setw(6) << k
             << setw(20) << a
             << setw(20) << sum << "\n";

        // while(true) - неескінченний цикл виходимо з нього через break
        while (true)
        {

            // РЕКУРЕНТНЕ СПІВВІДНОШЕННЯ:
            // a(k+1) = a(k) * ( -x^2 * (2k-1) ) / ( (2k+1) * (k+1) )
            //  - множник -x^2   : змінює знак і піднімає степінь x на 2
            //  - (2k-1)/(2k+1)  : міняє множник (2k-1) на (2k+1) у знаменнику
            //  - 1/(k+1)        : так з k! отримуємо (k+1)! без повного перерахунку
            // (double) потрібен, щоб ділення було дійсним, а не цілим
            a *= -(double)x * x * (2 * k - 1) / ((2.0 * k + 1) * (k + 1));

            k++; // переходимо до наступного номера члена

            double m = fabs(a); // модуль члена - для перевірок нижче

            // УМОВА ВИХОДУ:
            //  m < eps       - досягнуто заданої точності
            //  m < MIN_LIMIT - член занадто малий (захист від переповнення)
            //  m > MAX_LIMIT - член занадто великий (захист від переповнення)
            if (m < eps || m < MIN_LIMIT || m > MAX_LIMIT)
                break;

            // Додаємо член до накопиченої суми внутрішнього ряду
            sum += a;

            // Виводимо поточний рядок таблиці
            cout << setw(4) << x
                 << setw(6) << k
                 << setw(20) << a
                 << setw(20) << sum << "\n";
        }

        // Лінія-розділювач між блоками різних x
        cout << string(50, '-') << "\n";

        // Додаємо суму внутрішнього ряду до загальної (зовнішня сума)
        total += sum;
    }

    // ---------- 5. Підсумок ----------
    cout << "Загальна сума S = " << total << "\n";

    return 0; // 0 - програма завершилась успішно
}